// Helper calculations
export function getXpRequiredForLevel(level: number): number {
  return Math.floor(250 * Math.pow(level, 1.45));
}

export function getVehicleUpgradeCost(statKey: keyof Vehicle['currentUpgrades'], currentLevel: number, vehicleTier: number): number {
  const baseCost = 400 * vehicleTier;
  return Math.floor(baseCost * Math.pow(1.65, currentLevel));
}

export function getWeaponUpgradeCost(currentLevel: number, weaponType: Weapon['type']): number {
  const baseCost = weaponType === 'primary' ? 600 : 1200;
  return Math.floor(baseCost * Math.pow(1.7, currentLevel));
}

export function calculateVehicleActualStats(vehicle: Vehicle) {
  const u = vehicle.currentUpgrades;
  return {
    topSpeed: Math.round(vehicle.baseStats.topSpeed + u.topSpeed * 12),
    acceleration: +(vehicle.baseStats.acceleration + u.acceleration * 0.45).toFixed(1),
    handling: +(vehicle.baseStats.handling + u.handling * 0.4).toFixed(1),
    armor: Math.round(vehicle.baseStats.armor + u.armor * 5),
    health: Math.round(vehicle.baseStats.health + u.health * 35),
    nitro: +(vehicle.baseStats.nitro + u.nitro * 0.8).toFixed(1),
  };
}

export function calculateWeaponActualStats(weapon: Weapon) {
  const multiplier = 1 + (weapon.level - 1) * 0.28;
  return {
    damage: Math.round(weapon.damage * multiplier),
    fireRate: +(weapon.fireRate * (1 + (weapon.level - 1) * 0.1)).toFixed(1),
    range: Math.round(weapon.range * (1 + (weapon.level - 1) * 0.08)),
    ammoCapacity: Math.round(weapon.ammoCapacity * (1 + (weapon.level - 1) * 0.2)),
    cooldown: +(weapon.cooldown * Math.pow(0.9, weapon.level - 1)).toFixed(1),
  };
}
